def sum(a, b):
    """Calcule la somme de 2 entiers

    Args:
        a (int): premier entier
        b (int): second entier

    Returns:
        int: somme de 2 entiers
    """
    return a + b
 
def subtraction(a, b):
    """Soustrait b à a.

    Args:
        a (int): premier de départ
        b (int): entier à soustraire

    Returns:
        int: résultat de la soustraction
    """
    return a - b
